# Cached resources

@st.cache_resource(show_spinner=False)
def get_network():
    network = build_network()
    return network, compute_pipe_importance(network)

@st.cache_resource(show_spinner=False)
def get_models():
    """Load trained models; train them on first launch if they are missing."""
    if not models_exist():
        network, importance = get_network()
        with st.spinner("First launch: training AI models on simulated data (about 1 minute) ..."):
            detector, localizer, _ = train_models(network, progress=lambda message: None)
            save_models(detector, localizer, importance)
    return load_models()

@st.cache_data(show_spinner=False, max_entries=64)
def run_simulation(scenario_dict):
    network, _ = get_network()
    return simulate_scenario(network, ScenarioConfig(**scenario_dict))

def analyse(scenario_dict, cost_per_m3, currency):
    detector, localizer, importance = get_models()
    simulation = run_simulation(scenario_dict)
    return simulation, analyse_scenario(simulation, detector, localizer, importance,
                                        cost_per_m3, currency)

def load_metrics():
    if config.METRICS_PATH.exists():
        return json.loads(config.METRICS_PATH.read_text())
    return None

