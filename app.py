# TAB 6 - About and ethics

with tabs[5]:
    st.markdown("""
#### How AquaSentinel works
1. **Digital twin** – a simplified hydraulic model (Hazen-Williams head loss, linear-theory solver)
   predicts what every sensor *should* read given the demand forecast.
2. **Residuals** – measured minus expected readings remove the normal daily cycle.
3. **Isolation Forest + range check** – trained only on leak-free days. The forest flags unusual
   *combinations* of residuals; the range check flags a single sensor far outside its normal
   range (a known Isolation Forest blind spot). An alarm needs 3 consecutive anomalous
   readings (45 min).
4. **Random Forest** – trained on thousands of labelled simulated leaks, maps the residual
   "fingerprint" to the most likely leaking pipe.
5. **Impact** – extra inflow at the reservoir meter estimates leak size → water savings →
   repair priority (0.5 loss + 0.3 importance + 0.2 confidence).

#### Limitations
- The network, sensors, demand and leaks are **synthetic**. The solver is a simplified model and
  has **not** been validated against EPANET or field data.
- Models trained on simulated data will not transfer directly to a real network: real deployment
  needs real network data, sensor validation, recalibration and expert testing.
- AI scores are ranking scores, not calibrated probabilities.
- One leak at a time is assumed in each simulated day.

#### Ethics and responsible use
- No personal or real utility data is used. All values are labelled as simulated.
- AquaSentinel is a **decision-support prototype**, not an operational control system. Final repair
  decisions must stay with qualified engineers.
- Priority weights are transparent design choices that a utility should review with its
  stakeholders – e.g. to make sure low-income or remote areas are not systematically de-prioritised.
""")